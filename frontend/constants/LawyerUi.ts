export function getLawyerUi(language: string): LawyerUiStrings {
  return LAWYER_UI[language] || LAWYER_UI.en;
}

export function formatLawyerUi(template: string, values: Record<string, string | number>): string {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value)),
    template
  );
}
